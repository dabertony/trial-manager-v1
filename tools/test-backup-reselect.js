'use strict';
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const start = source.indexOf('function handleBackupImport(event)');
const end = source.indexOf('\nfunction ', start + 10);
if (start < 0 || end < 0) throw new Error('Backup import handler not found');
const handler = source.slice(start, end);
const fileRead = handler.indexOf('const file = input.files && input.files[0];');
const reset = handler.indexOf('input.value = "";');
const emptyGuard = handler.indexOf('if(!file){');
if (fileRead < 0) throw new Error('Backup handler must safely read the selected file');
if (reset < fileRead) throw new Error('Backup input must be reset only after capturing the selected file');
if (emptyGuard < reset) throw new Error('Backup input must be reset even when no file is selected');
if (!handler.includes('reader.readAsText(file)')) throw new Error('Captured file must still be passed to FileReader');
if (!handler.includes('askConfirm(')) throw new Error('Backup replacement confirmation must remain');
const resetCount = (handler.match(/input\.value = "";/g) || []).length;
if (resetCount !== 1) throw new Error('Backup input should be reset exactly once before asynchronous reading');
if (handler.indexOf('input.value = "";') > handler.indexOf('reader.readAsText(file)')) throw new Error('Backup input reset must happen before reading begins');
console.log('PASS: backup file input reset, same-file reselection, and confirmation checks passed.');
