'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'service-worker.js'), 'utf8');
let checks = 0;
function check(ok, message) { checks++; if (!ok) throw new Error(message); }
check(app.includes('function showAppNotice(message, type = "error")'), 'shared non-blocking notice helper should exist');
check(app.includes('notice.setAttribute("role", type === "error" ? "alert" : "status")'), 'notice should expose an accessible role');
check(app.includes('text.textContent = String(message || "Une erreur est survenue.")'), 'notice content should be assigned as text, not HTML');
check(app.includes('host.insertBefore(notice, host.firstChild)'), 'notice should be placed at the top of the app');
check(app.includes('showAppNotice("L\'export PDF n\'est pas disponible sur cet appareil.")'), 'PDF fallback should use a non-blocking notice');
check((app.match(/showAppNotice\(/g) || []).length >= 5, 'Excel/PDF error paths should use the shared notice helper');
check(!/\balert\s*\(/.test(app), 'blocking alert() calls should be removed from app.js');
check(index.includes('app.js?v=116'), 'index should request the updated application script');
check(sw.includes('trial-manager-cache-v127'), 'offline cache should be versioned for the update');
check(!index.includes("console.log('Service Worker enregistré')"), 'successful service-worker registration should not leave routine console noise');
check(index.includes(".catch(err => console.error('Service Worker erreur:', err))"), 'service-worker registration failures should remain diagnosable');
console.log(`PASS: ${checks} non-blocking notice checks passed.`);
