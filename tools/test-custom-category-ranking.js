'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const veteranCall = source.indexOf('"VETERAN",\n  veteranList,');
const customBlock = source.indexOf('// ===== CATÉGORIES PERSONNALISÉES =====');
const actionsBlock = source.indexOf('// ===== ACTIONS =====', customBlock);
assert(veteranCall >= 0, 'official veteran ranking should remain present');
assert(customBlock > veteranCall, 'custom rankings must appear after the veteran ranking');
assert(actionsBlock > customBlock, 'custom ranking block must be part of results before the function returns');
const block = source.slice(customBlock, actionsBlock);
assert(block.includes('(state.customCategories || []).forEach'), 'each saved custom category should receive its own ranking');
assert(block.includes('stats.filter(p =>'), 'custom ranking should include participants in that exact category');
assert(block.includes('applyTieBreaks(customList, c, categoryName)'), 'custom ranking should use the existing tie-break process');
assert(block.includes('customUfolepList.forEach'), 'custom categories must calculate a separate UFOLEP ranking');
assert(block.includes('Engine.getUfolepPoints(index + 1)'), 'custom categories must award points using the existing UFOLEP scale');
assert(block.includes('customProvisional'), 'custom ranking must preserve provisional status');
const championshipStart = source.indexOf('function buildChampionship(jokers)');
const championshipEnd = source.indexOf('function renderChampionshipTable(', championshipStart);
const championship = source.slice(championshipStart, championshipEnd);
assert(championship.includes('(state.customCategories || []).forEach'), 'custom categories must contribute to the championship');
assert(championship.includes('Engine.getUfolepPoints(ufoPos)'), 'championship custom categories must use UFOLEP points');
const showStart = source.indexOf('function showChampionship(jokers)');
const showEnd = source.indexOf('function printPDFPWA(', showStart);
const show = source.slice(showStart, showEnd);
assert(show.includes('renderChampionshipTable(\n      categoryName'), 'custom championship tables should be rendered after official groups');
const clubStart = source.indexOf('function buildClubChampionship()');
const club = source.slice(clubStart);
assert(!club.slice(0, club.indexOf('function ' , 20) > 0 ? club.indexOf('function ',20) : club.length).includes('state.customCategories'), 'club championship should not explicitly include custom categories');
console.log('PASS: custom categories have their own rankings with UFOLEP points, enter the validated-competition championship after official tables, and remain excluded from club rankings.');
