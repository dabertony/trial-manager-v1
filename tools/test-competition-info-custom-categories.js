"use strict";
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const source = fs.readFileSync(path.join(__dirname, "..", "app.js"), "utf8");
const start = source.indexOf("function showCompetitionInfo(i){");
const end = source.indexOf("// ===== PILOTES =====", start);
assert(start >= 0 && end > start, "competition info screen should exist");
const info = source.slice(start, end);
assert(info.includes("const customInfoCategories = []"), "custom categories should be collected dynamically");
assert(info.includes("(state.customCategories || []).forEach"), "all saved custom categories should be included");
const participants = info.indexOf("// PARTICIPANTS");
const participantCustom = info.indexOf("customInfoCategories.forEach(categoryName =>", participants);
const participantFemaleTotals = info.indexOf("totalF = c.participants.filter", participants);
assert(participantCustom > participants && participantCustom < participantFemaleTotals, "custom participant counts should appear after official N5 rows");
const abandon = info.indexOf("// ABANDONS");
const abandonCustom = info.indexOf("customInfoCategories.forEach(categoryName =>", abandon);
const abandonTotal = info.indexOf("<b>${totalAB}</b>", abandon);
assert(abandonCustom > abandon && abandonCustom < abandonTotal, "custom abandonment counts should be included before the total");
const tiebreak = info.indexOf("// DEPARTAGES");
const veteranRow = info.indexOf("VET", tiebreak);
const tiebreakCustom = info.indexOf("// Départages des catégories personnalisées, après VET.", tiebreak);
assert(tiebreakCustom > veteranRow, "custom tie-break summaries should follow VET");
const other = info.indexOf("➕ Autre");
const tourCustom = info.indexOf("// Détail des catégories personnalisées en bas de chaque fiche de tour.");
assert(other >= 0 && tourCustom > other, "tour info should show Other total before custom category rows");
assert(info.includes("BUILT_IN_CATEGORIES.includes(p.cat)"), "custom category names must not be double-counted in official category rows or gender totals");
console.log("PASS: custom categories are included in competition info participant, abandonment, tie-break and tour summaries in the requested order.");
