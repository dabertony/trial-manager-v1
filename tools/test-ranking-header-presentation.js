'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'style.css'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'service-worker.js'), 'utf8');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const svg = fs.readFileSync(path.join(root, 'ufolep-logo-lockup.svg'), 'utf8');
function check(ok, message) { if (!ok) throw new Error(message); }
check(app.includes('class="ranking-heading"'), 'ranking heading should use a shared layout');
check(app.includes('CLASSEMENT ${title}'), 'ranking category label should remain dynamic');
check(app.includes('getCategoryColor(title)'), 'ranking label should reuse category colors');
check(app.includes('src="ufolep-logo-lockup-print.png"'), 'ranking heading should include the local UFOLEP lockup');
check(app.includes('✔ Classement validé'), 'validated/provisional status should be retained');
check(!app.includes('class="print-footer"'), 'redundant line under ranking status should be removed');
check(css.includes('.ranking-category-label') && css.includes('border:1px solid #111827'), 'category label should have a black border, including white N4');
check(css.includes('.ufolep-ranking-logo'), 'logo should be sized for screen and print');
check(/\.ufolep-ranking-logo\s*\{[^}]*right:\s*2%/s.test(css), 'logo should be anchored near the right edge without affecting title flow');
check(/width:\s*210px/.test(css), 'screen logo should be larger and overlaid without taking layout space');
check(/width:\s*198px/.test(css), 'print logo should remain large');
check(/page-break-inside:avoid/.test(css), 'print ranking header should not split across pages');
check(/max-width:calc\(65% - 110px\)/.test(css), 'print title should have more width to avoid wrapping');
check(/\.ranking-heading\s*\{[^}]*min-height:80px/s.test(css), 'print header should reserve room for the overlaid logo to prevent page splitting');
check(/pointer-events:none/.test(css), 'overlaid logo should not interfere with interactions');
check(sw.includes('./ufolep-logo-lockup.svg'), 'logo should be available offline');
check(pkg.scripts.test.includes('test-ranking-header-presentation.js'), 'ranking header test should be part of npm test');
check(svg.includes('TOUS LES SPORTS') && svg.includes('AUTREMENT'), 'logo lockup should include the UFOLEP tagline');
console.log('PASS: ranking header presentation checks passed (10 checks).');
